<?php
/**
 * FaceTube - Get User Certificate API
 * GET /api/certificates/get.php?userId={userId}
 */

require_once __DIR__ . '/../config/database.php';
require_once __DIR__ . '/../response.php';

$pdo = getDatabaseConnection();
$userId = strtoupper(trim($_GET['userId'] ?? ($_GET['user_id'] ?? '')));

if (empty($userId)) {
    $authUser = getAuthUser($pdo);
    if ($authUser) {
        $userId = strtoupper($authUser['user_id']);
    }
}

if (empty($userId)) {
    jsonResponse(['success' => false, 'error' => 'User ID is required.'], 400);
}

$stmt = $pdo->prepare('
    SELECT id, certificate_id, user_id, creator_name, channel_name, rank_id, award_name, subscribers, badge, issue_date, created_at
    FROM certificates
    WHERE UPPER(user_id) = ?
    ORDER BY created_at DESC
    LIMIT 1
');
$stmt->execute([$userId]);
$cert = $stmt->fetch();

if (!$cert) {
    // Check user info to produce standard milestone representation
    $uStmt = $pdo->prepare('SELECT name, user_id FROM users WHERE UPPER(user_id) = ? LIMIT 1');
    $uStmt->execute([$userId]);
    $u = $uStmt->fetch();
    $name = $u['name'] ?? 'Creator';

    $cert = [
        'certificateId' => "FT-CERT-2026-GOLD-" . substr(md5($userId), 0, 6),
        'userId' => $userId,
        'creatorName' => $name,
        'channelName' => "{$name} Official",
        'rankId' => 'level-4',
        'awardName' => 'Gold Creator Award',
        'subscribers' => 100000,
        'badge' => '🥇',
        'issueDate' => 'October 08, 2026',
        'isAutoGenerated' => true,
    ];
} else {
    $cert = [
        'id' => $cert['id'],
        'certificateId' => $cert['certificate_id'],
        'userId' => $cert['user_id'],
        'creatorName' => $cert['creator_name'],
        'channelName' => $cert['channel_name'],
        'rankId' => $cert['rank_id'],
        'awardName' => $cert['award_name'],
        'subscribers' => (int)$cert['subscribers'],
        'badge' => $cert['badge'],
        'issueDate' => $cert['issue_date'],
        'createdAt' => $cert['created_at'],
        'isAutoGenerated' => false,
    ];
}

jsonResponse(['success' => true, 'certificate' => $cert]);
